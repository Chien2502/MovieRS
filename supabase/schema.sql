ALTER TABLE moviers.feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE moviers.favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE moviers.watch_progress ENABLE ROW LEVEL SECURITY;

-- Đánh dấu phiên bản bootstrap chỉ sau khi toàn bộ cấu trúc đã được tạo.
CREATE TABLE IF NOT EXISTS moviers.schema_version (
    version text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE moviers.schema_version ENABLE ROW LEVEL SECURITY;
INSERT INTO moviers.schema_version(version) VALUES ('001_initial') ON CONFLICT DO NOTHING;

-- Phiên opaque chỉ lưu digest; không lưu bearer token trong database.
CREATE TABLE IF NOT EXISTS moviers.sessions (
    token_hash text PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
    user_id bigint NOT NULL REFERENCES moviers.app_users(user_id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON moviers.sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expires_idx ON moviers.sessions(expires_at);
ALTER TABLE moviers.sessions ENABLE ROW LEVEL SECURITY;
