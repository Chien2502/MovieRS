-- Schema riêng cho FastAPI; không mở dữ liệu ứng dụng trực tiếp qua public Data API.
-- Chạy bằng database owner từ SQL Editor hoặc src/data/init_database.py.
CREATE SCHEMA IF NOT EXISTS moviers;
REVOKE ALL ON SCHEMA moviers FROM PUBLIC;

CREATE TABLE IF NOT EXISTS moviers.app_users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 200000) PRIMARY KEY,
    username text NOT NULL CHECK (char_length(btrim(username)) BETWEEN 3 AND 50),
    password_hash text NOT NULL,
    salt text NOT NULL,
    genres text[] NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT app_users_id_range CHECK (user_id >= 200000)
);
CREATE UNIQUE INDEX IF NOT EXISTS app_users_username_lower_idx
    ON moviers.app_users (lower(username));

CREATE TABLE IF NOT EXISTS moviers.movies (
    movie_id bigint PRIMARY KEY CHECK (movie_id > 0),
    tmdb_id bigint,
    title text NOT NULL,
    genres text[] NOT NULL DEFAULT '{}',
    poster_path text NOT NULL DEFAULT '',
    overview text NOT NULL DEFAULT '',
    vote_average numeric(3,1) NOT NULL DEFAULT 0 CHECK (vote_average BETWEEN 0 AND 10),
    vote_count bigint NOT NULL DEFAULT 0 CHECK (vote_count >= 0),
    release_date date,
    runtime_minutes integer NOT NULL DEFAULT 100 CHECK (runtime_minutes > 0),
    release_year integer CHECK (release_year BETWEEN 0 AND 9999)
);

-- Một phản hồi hiệu lực trên mỗi cặp user-phim; giữ nguồn để bảo toàn nghĩa số sao.
CREATE TABLE IF NOT EXISTS moviers.feedback (
    user_id bigint NOT NULL REFERENCES moviers.app_users(user_id) ON DELETE CASCADE,
    movie_id bigint NOT NULL REFERENCES moviers.movies(movie_id) ON DELETE CASCADE,
    rating numeric(2,1) NOT NULL CHECK (rating BETWEEN 0.5 AND 5.0),
    source text NOT NULL CHECK (source IN ('explicit', 'legacy_unknown', 'favorite', 'watch', 'watch_complete')),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, movie_id)
);
CREATE INDEX IF NOT EXISTS feedback_movie_idx ON moviers.feedback(movie_id);
CREATE INDEX IF NOT EXISTS feedback_updated_idx ON moviers.feedback(updated_at);

CREATE TABLE IF NOT EXISTS moviers.favorites (
    user_id bigint NOT NULL REFERENCES moviers.app_users(user_id) ON DELETE CASCADE,
    movie_id bigint NOT NULL REFERENCES moviers.movies(movie_id) ON DELETE CASCADE,
    added_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, movie_id)
);
CREATE INDEX IF NOT EXISTS favorites_movie_idx ON moviers.favorites(movie_id);

CREATE TABLE IF NOT EXISTS moviers.watch_progress (
    user_id bigint NOT NULL REFERENCES moviers.app_users(user_id) ON DELETE CASCADE,
    movie_id bigint NOT NULL REFERENCES moviers.movies(movie_id) ON DELETE CASCADE,
    position_seconds bigint NOT NULL CHECK (position_seconds >= 0),
    duration_seconds bigint NOT NULL CHECK (duration_seconds > 0),
    ratio double precision GENERATED ALWAYS AS
        (position_seconds::double precision / duration_seconds) STORED,
    status text GENERATED ALWAYS AS
        (CASE WHEN position_seconds::numeric / duration_seconds >= 0.95
              THEN 'finished' ELSE 'in_progress' END) STORED,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, movie_id),
    CHECK (position_seconds <= duration_seconds)
);
CREATE INDEX IF NOT EXISTS watch_progress_movie_idx ON moviers.watch_progress(movie_id);
CREATE INDEX IF NOT EXISTS watch_progress_user_updated_idx
    ON moviers.watch_progress(user_id, updated_at DESC);

-- Chưa có cơ chế xác thực Supabase Auth: không tạo policy mở cho anon/authenticated.
